// Fisher-Yates Shuffle helper
function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// Session-persisted used question tracker
const STORAGE_KEY = 'gnr_used_questions_v1';

function getUsedQuestionIds(): Set<string> {
  if (typeof window === 'undefined') return new Set();
  try {
    const raw = sessionStorage.getItem(STORAGE_KEY);
    if (!raw) return new Set();
    const parsed = JSON.parse(raw);
    return new Set(Array.isArray(parsed) ? parsed : []);
  } catch {
    return new Set();
  }
}

function saveUsedQuestionIds(ids: Set<string>): void {
  if (typeof window === 'undefined') return;
  try {
    sessionStorage.setItem(STORAGE_KEY, JSON.stringify(Array.from(ids)));
  } catch {}
}

/**
 * Gets N guaranteed unique, non-repeating questions from the 125-question master pool.
 * If the pool has been exhausted during a marathon session, it cycles back cleanly.
 */
export function getNonRepeatingQuestions(count: number): RailwayChallenge[] {
  const usedIds = getUsedQuestionIds();
  let available = MASTER_QUESTION_POOL.filter((q) => !usedIds.has(q.id));

  // If available questions are fewer than needed, reset the session used list
  if (available.length < count) {
    usedIds.clear();
    saveUsedQuestionIds(usedIds);
    available = [...MASTER_QUESTION_POOL];
  }

  // Shuffle available questions
  const shuffled = shuffleArray(available);
  const selected = shuffled.slice(0, count);

  // Mark selected as used for this session
  selected.forEach((q) => usedIds.add(q.id));
  saveUsedQuestionIds(usedIds);

  return selected;
}
