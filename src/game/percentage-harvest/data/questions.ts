/** Shuffles questions and returns a tailored match for a team (5, 10, or 15 questions) */
export function getMatchQuestions(totalQuestions: 5 | 10 | 15 = 5, seedOffset = 0): PercentageQuestion[] {
  const round1Pool = ALL_QUESTIONS.filter((q) => q.roundNumber === 1);
  const round2Pool = ALL_QUESTIONS.filter((q) => q.roundNumber === 2);
  const round3Pool = ALL_QUESTIONS.filter((q) => q.roundNumber === 3);
  const round4Pool = ALL_QUESTIONS.filter((q) => q.roundNumber === 4);
  const round5Pool = ALL_QUESTIONS.filter((q) => q.roundNumber === 5);

  const pools = [round1Pool, round2Pool, round3Pool, round4Pool, round5Pool];
  const questionsPerStage = totalQuestions / 5;
  const matchQuestions: PercentageQuestion[] = [];

  for (let stageIdx = 0; stageIdx < 5; stageIdx++) {
    const pool = pools[stageIdx];
    for (let qIdx = 0; qIdx < questionsPerStage; qIdx++) {
      const selected = pool[(stageIdx * 3 + qIdx + seedOffset) % pool.length];
      matchQuestions.push(selected);
    }
  }

  return matchQuestions;
}
