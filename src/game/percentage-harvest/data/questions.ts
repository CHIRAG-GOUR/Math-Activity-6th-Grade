/**
 * Shuffles and retrieves diverse, tailored match questions (5, 10, or 15 questions)
 * Guarantees at least 2 hectare-filling / grid questions in any 5-question match
 * (and proportionately 4 in 10-question, 6 in 15-question matches),
 * while dynamically picking fresh random questions on every load/restart.
 */
export function getMatchQuestions(
  totalQuestions: 5 | 10 | 15 = 5,
  seedOffset: number = Math.floor(Math.random() * 10000)
): PercentageQuestion[] {
  const roundPools: { grid: PercentageQuestion[]; standard: PercentageQuestion[] }[] = [];

  for (let r = 1; r <= 5; r++) {
    const roundAll = ALL_QUESTIONS.filter((q) => q.roundNumber === r);
    const grid = roundAll.filter((q) => q.mode === 'grid100' || q.category === 'grid100');
    const standard = roundAll.filter((q) => q.mode !== 'grid100' && q.category !== 'grid100');
    roundPools.push({ grid, standard });
  }

  // Determine minimum number of grid questions to include:
  // 5 questions: at least 2 grid questions (e.g. 2 grid, 3 standard)
  // 10 questions: at least 4 grid questions
  // 15 questions: at least 6 grid questions
  const minGridCount = totalQuestions === 5 ? 2 : totalQuestions === 10 ? 4 : 6;
  const questionsPerStage = totalQuestions / 5;

  // Decide which stages will feature grid questions
  // For a 5-question match (1 question per stage), randomly select 2 stages to be grid questions
  const stagesForGrid = new Set<number>();
  const availableStages = [0, 1, 2, 3, 4];

  // Random permutation of stages
  for (let i = availableStages.length - 1; i > 0; i--) {
    const j = Math.floor((Math.abs(Math.sin(seedOffset + i * 19.17 + Math.random())) * 10000) % (i + 1));
    [availableStages[i], availableStages[j]] = [availableStages[j], availableStages[i]];
  }

  for (let i = 0; i < Math.min(minGridCount, availableStages.length); i++) {
    stagesForGrid.add(availableStages[i]);
  }

  const result: PercentageQuestion[] = [];

  for (let stageIdx = 0; stageIdx < 5; stageIdx++) {
    const { grid, standard } = roundPools[stageIdx];
    const isGridStage = stagesForGrid.has(stageIdx);

    for (let qIdx = 0; qIdx < questionsPerStage; qIdx++) {
      let chosenPool = standard;
      if (isGridStage && (qIdx === 0 || grid.length >= questionsPerStage)) {
        chosenPool = grid.length > 0 ? grid : standard;
      }

      // Pick a random question from the chosenPool
      const randIndex = Math.floor(
        (Math.abs(Math.sin(seedOffset + stageIdx * 37 + qIdx * 13 + Math.random())) * 10000) % chosenPool.length
      );
      result.push(chosenPool[randIndex]);
    }
  }

  return result;
}
